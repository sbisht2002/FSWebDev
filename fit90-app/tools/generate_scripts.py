def breath_block(inn, out, n, text_in="Breathe in", text_out="And out, slowly", hold=0):
    lines = [f"[repeat {n}]", f"[in {inn}] {text_in}"]
    if hold: lines.append(f"[hold {hold}]")
    lines += [f"[out {out}] {text_out}", "[/repeat]"]
    return lines

def bodyscan(level):
    parts = BODY if level >= 3 else BODY[::2] + [BODY[-1]]
    l = [SETTLE[level % 6], "[pause 4]", "Let your breathing find its own easy rhythm.", "[pause 4]"]
    l += breath_block(4, 6, 3)
    l.append("Now we'll move attention slowly through the body. Wherever it lands, simply notice what's there.")
    for i, p in enumerate(parts):
        l.append(f"Bring your attention to {p}. Notice warmth or coolness, pressure, tingling, or nothing at all.")
        if level >= 2: l.append("If you find tension, breathe towards it, and let it soften on the out-breath.")
        l.append("[pause 6]")
    l += ["Now notice your whole body at once, breathing.", "[pause 8]",
          "If your mind wandered at any point, that's fine. Noticing and coming back is the practice.", "[pause 4]",
          CLOSE[level % 4], "[chime]"]
    return l

def calm(level):
    l = [SETTLE[(level + 2) % 6], "[pause 3]",
         "This is a short routine to settle your body before being close to someone. Nothing needs to happen afterwards. It's just for you.",
         "[pause 3]", "Let's start by slowing the breath, with a longer breath out."]
    l += breath_block(4, 7, 4 + level)
    l += ["Now scan for tension. Unclench your jaw.", "[pause 3]", "Let your shoulders drop.", "[pause 3]",
          "Soften your belly. Let it move freely as you breathe.", "[pause 3]",
          "And let the base of your body, your pelvic floor, soften and drop on the in-breath.", "[pause 3]"]
    l += breath_block(4, 6, 3, "Breathe in, let it drop and soften", "Breathe out, let it settle")
    thoughts = ["If anxious thoughts appear, notice them like clouds passing. You don't have to follow them.",
                "Remind yourself: there's no test tonight. Closeness, touch and enjoying each other are enough.",
                "Choose one thing you appreciate about your partner, and let yourself feel it.",
                "Imagine bringing curiosity rather than pressure: noticing what feels good, moment by moment.",
                "If things don't go as planned, you can slow down, breathe and stay close. That's always an option.",
                "Let your attention rest on sensation: warmth, touch, breath. That's where enjoyment lives."]
    for t in thoughts[:2 + level // 2]:
        l += [t, "[pause 5]"]
    l += breath_block(4, 6, 3)
    l += ["You've given your body a chance to settle. Carry this slower breathing with you.", "[chime]"]
    return l

def confidence(level):
    themes = [
        ("Noticing thoughts", ["Bring to mind a recent moment when you felt anxious about intimacy, nothing too intense.",
         "Notice the thoughts that came with it. You might hear, \"What if it happens again?\"",
         "Now, silently add the words: \"I'm having the thought that...\" in front of it.",
         "Notice the small gap that creates. You are the one noticing the thought. You are not the thought."]),
        ("Kinder words", ["Imagine a good friend telling you about the same worry you have.",
         "Notice what you'd say to them. Probably something patient and understanding.",
         "Now offer yourself those same words, in the same tone.",
         "You might say: \"This is hard, lots of people go through it, and I'm doing my best.\""]),
        ("Back to the body", ["When worry pulls you into your head, your body is always here to come back to.",
         "Feel your hands. Their weight, their warmth.", "Feel your breath moving in your belly.",
         "This is the skill: notice you've drifted, and gently come back to sensation."]),
        ("Balanced thoughts", ["Think of an anxious prediction, like \"I'll let them down.\"",
         "Ask: is this a fact, or a guess?", "What would be a more balanced way to see it?",
         "Perhaps: \"I don't know what will happen, and I can handle it either way.\""]),
        ("Small steps", ["Picture one small step that would build your confidence, something only a little uncomfortable.",
         "Imagine yourself taking it calmly, breathing slowly.", "Notice the anxiety rise a little, and then settle.",
         "Each small step teaches your brain that you can cope."]),
        ("Letting go of the score", ["Notice any urge to measure yourself: how long, how hard, how good.",
         "Imagine setting the scoreboard down.", "What's left is two people, warmth, touch and curiosity.",
         "That is enough."]),
    ]
    title, lines = themes[(level - 1) % len(themes)]
    l = [SETTLE[(level + 1) % 6], "[pause 3]"] + breath_block(4, 6, 3) + [f"Today's practice: {title.lower()}.", "[pause 2]"]
    for t in lines:
        l += [t, "[pause 6]"]
    l += ["Take a slow breath, and notice how you feel now compared with when you started.", "[pause 5]",
          "Confidence grows with practice, not perfection.", CLOSE[(level + 1) % 4], "[chime]"]
    return l, title

def arousal(level):
    l = [SETTLE[level % 6], "[pause 3]",
         "This practice builds awareness of tension and calm in your body. It is done fully clothed, simply sitting or lying down.",
         "[pause 2]", "Imagine a scale from zero to ten for how activated your body feels right now, where zero is completely calm.",
         "Give yourself a number. There's no right answer.", "[pause 5]",
         "Notice the signs that tell you: your breathing, your heart rate, tension in your belly, buttocks and pelvic floor.",
         "[pause 5]", "Now let's practise bringing the number down."]
    l += breath_block(4, 7, 4 + level, "Breathe in slowly", "Breathe out, and let your body soften")
    l += ["Check your number again. Has it changed, even a little?", "[pause 5]",
          "Now gently squeeze the pelvic floor for a moment, and notice how that tension feels.",
          "[squeeze 3] Squeeze", "[release 5] And let it go completely. Notice the difference.", "[pause 3]"]
    if level >= 3:
        l += ["Practise the drop: as you breathe in, let the pelvic floor soften and lower."]
        l += breath_block(4, 6, 4, "Breathe in, let it drop", "Breathe out, settle")
    if level >= 5:
        l += ["Imagine a moment when you felt yourself getting tense and rushed. Notice the number climb.", "[pause 5]",
              "Now use your breath and the drop to bring it back down, staying with the scene.", "[pause 8]"]
    l += ["This is the skill you'll use later: notice the number, and slow down early. Well done.", "[chime]"]
    return l

def sleep(level):
    l = ["Lie down comfortably and let the bed take your weight. Turn down the lights if you can.", "[pause 4]",
         "There's nothing to achieve now. Just let the day finish."]
    l += breath_block(4, 8, 4 + level, "Breathe in gently", "And a long, slow breath out")
    for p in BODY[::-1][: 6 + level]:
        l += [f"Let {p} grow heavy and warm.", "[pause 6]"]
    l += ["If thoughts about tomorrow arrive, imagine placing them on a shelf. They'll be there in the morning.", "[pause 8]",
          "Let your breathing slow down on its own.", "[pause 10]", "Rest now.", "[pause 10]"]
    return l

def pelvic(level, cfg):
    s, r, h, rest, fl, dr = cfg
    l = ["Lie on your back with knees bent, or sit upright. Empty your bladder first if you need to.", "[pause 2]",
         "Remember: squeeze and lift as if holding in wind, keep breathing, and keep your buttocks, thighs and belly soft.",
         "[pause 2]"]
    l += breath_block(4, 6, 2)
    for k in range(s):
        l += [f"Set {k + 1}.", f"[repeat {r}]", f"[squeeze 2] Squeeze and lift"]
        if h > 2: l.append(f"[hold {h - 2}] Hold, breathing normally")
        l += [f"[release {rest}] Release fully", "[/repeat]"]
        if k < s - 1: l += ["[rest 20] Rest. Breathe slowly."]
    if fl:
        l += ["Quick flicks: squeeze fast, let go fully.", f"[repeat {fl}]", "[flick 1]", "[release 1]", "[/repeat]"]
    l += ["Finish with drops. Breathe in and let the pelvic floor soften and lower."]
    l += [f"[repeat {dr}]", "[drop 5] Breathe in, let it drop", "[out 5] Breathe out, settle", "[/repeat]",
          "Well done. Stop if anything ever hurts.", "[chime]"]
    return l

BREATH = {"slow": ("Slow breathing", 4, 6, 0), "box": ("Box breathing", 4, 4, 4),
          "extended": ("Extended exhale", 4, 8, 0), "sigh": ("Physiological sigh", 2, 6, 0)}

def breath(pid, minutes):
    name, inn, out, hold = BREATH[pid]
    cycle = inn + out + hold * 2 + (1 if pid == "sigh" else 0)
    n = max(3, int((minutes * 60 - 30) / cycle))
    l = [SETTLE[len(pid) % 6], "[pause 2]", f"This is {name.lower()}. Follow the cues, and breathe through your nose if you can."]
    l.append(f"[repeat {n}]")
    if pid == "sigh":
        l += [f"[in 2] Breathe in", "[in 1] And a little more", f"[out {out}] Long breath out"]
    elif pid == "box":
        l += [f"[in {inn}] In", f"[hold {hold}] Hold", f"[out {out}] Out", f"[holdout {hold}] Hold"]
    else:
        l += [f"[in {inn}] In", f"[out {out}] Out"]
    l += ["[/repeat]", "Let your breathing return to normal. Notice how you feel.", "[chime]"]
    return l, name

PELVIC_LEVELS = [(2, 8, 3, 3, 0, 5), (3, 8, 3, 3, 5, 5), (3, 10, 4, 4, 8, 6), (3, 10, 5, 5, 10, 6),
                 (3, 10, 6, 6, 10, 8), (3, 12, 6, 6, 12, 8), (3, 12, 8, 8, 15, 8), (3, 10, 10, 10, 15, 10),
                 (4, 10, 10, 10, 20, 10), (4, 12, 10, 10, 20, 10)]

def main(out, all_=False):
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.endswith(".md"): os.remove(os.path.join(out, f))
    count = 0
    levels6 = range(1, 7)
    for lv, cfg in enumerate(PELVIC_LEVELS, 1):
        minutes = max(3, round(seconds(pelvic(lv, cfg)) / 60))
        write(out, f"pelvic-{lv}", f"Guided pelvic floor · level {lv}", "pelvic", min(6, (lv + 1) // 2 + 0), minutes,
              "Spoken cues for every squeeze, hold and release", "none", pelvic(lv, cfg)); count += 1
    for pid in BREATH:
        for i, m in enumerate([3, 5, 10] + ([2, 7, 15] if all_ else [])):
            lines, name = breath(pid, m)
            write(out, f"breath-{pid}-{m}", f"{name} · {m} min", "breath", min(6, i + 1), m, "Paced breathing with voice cues",
                  "none", lines); count += 1
    for lv in levels6:
        write(out, f"scan-{lv}", f"Body scan · level {lv}", "bodyscan", lv, 4 + lv * 2, "Notice sensation without judging",
              "drone", bodyscan(lv)); count += 1
        write(out, f"aware-{lv}", f"Arousal awareness · level {lv}", "arousal", lv, 5 + lv, "Notice tension and calm on a 0–10 scale",
              "none", arousal(lv)); count += 1
        write(out, f"calm-{lv}", f"Pre-intimacy calm · level {lv}", "calm", lv, 3 + (lv + 1) // 2, "Settle your body first, no pressure",
              "drone", calm(lv)); count += 1
    for lv in range(1, 11 if not all_ else 31):
        lines, title = confidence(lv)
        write(out, f"conf-{lv}", f"Confidence: {title}", "confidence", min(6, (lv + 1) // 2), 6 + lv % 4, "A short CBT-style practice",
              "drone", lines); count += 1
    for lv in range(1, 11 if not all_ else 31):
        write(out, f"sleep-{lv}", f"Sleep wind-down · {lv}", "sleep", min(6, (lv + 1) // 2), 8 + lv % 5, "Let the day finish",
              "drone", sleep(min(6, lv))); count += 1
    if all_:
        for lv in range(7, 31):
            write(out, f"scan-{lv}", f"Body scan · {lv}", "bodyscan", 6, 6 + lv % 10, "Notice sensation without judging", "drone", bodyscan(6)); count += 1
            write(out, f"calm-{lv}", f"Pre-intimacy calm · {lv}", "calm", 6, 3 + lv % 3, "Settle your body first", "drone", calm(6)); count += 1
    print(f"Wrote {count} scripts to {out}")

if __name__ == "__main__":
    main(sys.argv[1], "--all" in sys.argv)
