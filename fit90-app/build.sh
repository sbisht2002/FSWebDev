#!/usr/bin/env bash
# Builds Fit90.apk with plain SDK tools (no Gradle, no Google downloads).
#
#   sudo apt-get install aapt dalvik-exchange apksigner zipalign default-jdk python3-pip
#   pip install -r tools/requirements.txt      # reportlab, for the PDF guides
#   ./build.sh
#
# Feature flags (environment variables):
#   AI_COACH_ENABLED=true|false   show the AI coach (default false)
#   COACH_URL=https://...          coach proxy endpoint (required when the coach is enabled)
#   COACH_NAME=Kai                 the coach's display name
#   AUDIO_BASE_URL=https://...     where pre-rendered audio can be downloaded from (optional)
#   SKIP_PDFS=1                    reuse the PDF guides from the previous build
set -euo pipefail
cd "$(dirname "$0")"

VERSION_CODE="${VERSION_CODE:-10}"
VERSION_NAME="${VERSION_NAME:-2.0}"
AI_COACH_ENABLED="${AI_COACH_ENABLED:-false}"
COACH_URL="${COACH_URL:-}"
COACH_NAME="${COACH_NAME:-Kai}"
AUDIO_BASE_URL="${AUDIO_BASE_URL:-}"
KEYSTORE="${KEYSTORE:-debug.keystore}"
BUILD_TOOLS="${BUILD_TOOLS:-/usr/lib/android-sdk/build-tools/debian}"
OUT=build
APK=Fit90.apk

if [ "$AI_COACH_ENABLED" = "true" ] && [ -z "$COACH_URL" ]; then
    echo "AI_COACH_ENABLED=true needs COACH_URL (your deployed coach proxy)." >&2
    exit 1
fi

SDK_CACHE="$(./tools/fetch_sdk.sh | tail -1)"
ANDROID_RES="$SDK_CACHE/android-33-res.jar"
ANDROID_CLASSES="$SDK_CACHE/android-all-15.jar"

echo "==> Checking content"
python3 tools/content_qa.py content

rm -rf "${OUT:?}/gen" "${OUT:?}/classes" "${OUT:?}/dex" "${OUT:?}/assets/content"
rm -f "${OUT:?}/unsigned.apk" "${OUT:?}/aligned.apk"
mkdir -p "$OUT/gen/com/fswebdev/fit90" "$OUT/classes" "$OUT/dex" "$OUT/assets"

echo "==> Packing content"
python3 tools/build_content.py content "$OUT/assets/content"
if [ "${SKIP_PDFS:-0}" != "1" ]; then
    echo "==> Building PDF guides"
    python3 tools/build_pdfs.py content "$OUT/assets/pdf"
fi
if [ -d audio-rendered ]; then
    mkdir -p "$OUT/assets/audio"
    cp audio-rendered/*.* "$OUT/assets/audio/" 2>/dev/null || true
fi

INTERNET=""
if [ "$AI_COACH_ENABLED" = "true" ] || [ -n "$AUDIO_BASE_URL" ]; then
    INTERNET='    <uses-permission android:name="android.permission.INTERNET" />'
fi
sed -e "s|@VERSION_CODE@|$VERSION_CODE|" -e "s|@VERSION_NAME@|$VERSION_NAME|" \
    -e "s|@INTERNET_PERMISSION@|$INTERNET|" AndroidManifest.xml.in > "$OUT/AndroidManifest.xml"

cat > "$OUT/gen/com/fswebdev/fit90/BuildConfig.java" <<JAVA
package com.fswebdev.fit90;

/** Generated by build.sh. Do not edit. */
public final class BuildConfig {
    public static final String VERSION_NAME = "$VERSION_NAME";
    public static final int VERSION_CODE = $VERSION_CODE;
    public static final boolean AI_COACH_ENABLED = $AI_COACH_ENABLED;
    public static final String COACH_URL = "$COACH_URL";
    public static final String COACH_NAME = "$COACH_NAME";
    public static final String AUDIO_BASE_URL = "$AUDIO_BASE_URL";

    private BuildConfig() {
    }
}
JAVA

echo "==> Packaging resources"
"$BUILD_TOOLS/aapt" package -f -m \
    -J "$OUT/gen" \
    -M "$OUT/AndroidManifest.xml" \
    -S res \
    -A "$OUT/assets" \
    -I "$ANDROID_RES" \
    -0 pdf -0 ogg -0 mp3 -0 m4a \
    -F "$OUT/unsigned.apk"

echo "==> Compiling Java"
javac --release 8 -nowarn -encoding UTF-8 -Xlint:-options \
    -classpath "$ANDROID_CLASSES" \
    -d "$OUT/classes" \
    $(find src "$OUT/gen" -name '*.java')

echo "==> Converting to dex"
"$BUILD_TOOLS/dx" --dex --min-sdk-version=23 --output="$OUT/dex/classes.dex" "$OUT/classes"
(cd "$OUT/dex" && zip -q -u ../unsigned.apk classes.dex)

echo "==> Aligning"
zipalign -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

if [ ! -f "$KEYSTORE" ]; then
    echo "==> Creating debug keystore"
    keytool -genkeypair -keystore "$KEYSTORE" -storepass android -keypass android \
        -alias androiddebugkey -keyalg RSA -keysize 2048 -validity 10000 \
        -dname "CN=Android Debug,O=Android,C=US" >/dev/null 2>&1
fi

echo "==> Signing"
apksigner sign --ks "$KEYSTORE" --ks-pass "pass:${KS_PASS:-android}" --key-pass "pass:${KEY_PASS:-android}" \
    --out "$APK" "$OUT/aligned.apk"
rm -f "$APK.idsig"
apksigner verify "$APK"

echo "Built $(pwd)/$APK"
